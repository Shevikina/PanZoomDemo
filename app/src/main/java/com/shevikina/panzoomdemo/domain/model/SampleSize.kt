package com.shevikina.panzoomdemo.domain.model

/**
 * Пороги выбора `inSampleSize` по масштабу с гистерезисом +-10 %:
 * исключает «дрожание» LOD у границы.
 *
 * Полосы стабильности:
 * - ss=1 при scale>=0.45
 * - ss=2 при 0.55-0.22
 * - ss=4 при 0.28-0.11
 * - ss=8 при scale<0.14
 *
 * Гистерезис LOD: пороги up/down раздвинуты на +-10 % от центральной точки.
 * - up - при zoom-in уменьшаем sampleSize;
 * - down - при zoom-out увеличиваем.
 *
 * Центры:
 * - 0.5
 * - 0.25
 * - 0.125
 */
object SampleSize {

    /** Полное разрешение. */
    const val MIN = 1

    /** Половина разрешения по каждой стороне. */
    const val HALF = 2

    /** Четверть. */
    const val QUARTER = 4

    /** Одна восьмая: самый грубый уровень, используется при сильном zoom-out. */
    const val EIGHTH = 8

    /** 3 подряд вызова ~= 50 мс на 60 Гц; страхует от LOD-перещелкиваний при быстрых "щипках"(pinch-ах) */
    const val STABLE_INVOCATIONS = 3

    /**
     * Порог scale перехода детализации тайлов вниз ss1 → ss2.
     *
     * Центральная точка: 0.5
     * Гистерезис LOD при zoom-in: -10%(-0.05)
     * */
    const val THRESHOLD_DOWN_FROM_1 = 0.45f

    /**
     * Порог scale перехода детализации тайлов вверх ss2 → ss1.
     *
     * Центральная точка: 0.5
     * Гистерезис LOD при zoom-out: +10%(+0.05)
     * */
    const val THRESHOLD_UP_FROM_2 = 0.55f

    /**
     * Порог scale перехода детализации тайлов вниз ss2 → ss4.
     *
     * Центральная точка: 0.25
     * Гистерезис LOD при zoom-in: -10%(-0.03)
     * */
    const val THRESHOLD_DOWN_FROM_2 = 0.22f

    /**
     * Порог scale перехода детализации тайлов вверх ss4 → ss2.
     *
     * Центральная точка: 0.25
     * Гистерезис LOD при zoom-out: +10%(+0.03)
     * */
    const val THRESHOLD_UP_FROM_4 = 0.28f

    /**
     * Порог scale перехода детализации тайлов вниз ss4 → ss8.
     *
     * Центральная точка: 0.125
     * Гистерезис LOD при zoom-in: -10%(-0.015)
     * */
    const val THRESHOLD_DOWN_FROM_4 = 0.11f

    /** Порог scale перехода детализации тайлов вверх ss8 → ss4.
     *
     * Центральная точка: 0.125.
     * Гистерезис LOD при zoom-out: +10%(+0.015)
     * */
    const val THRESHOLD_UP_FROM_8 = 0.14f
}
