package com.shevikina.panzoomdemo.domain.model

/**
 * Декодированное растровое изображение, буфер которого обязан освободить владелец.
 *
 * Тайлом быть не обязано. Тем же типом представлены вся картинка в наивном режиме
 * и overview-подложка, потому что способ освобождения у них разный, а контракт один.
 */
interface DecodedImage {

    val width: Int

    val height: Int

    /** Освобождает буфер так, как решил его создатель. После вызова изображение непригодно. */
    fun release()
}
